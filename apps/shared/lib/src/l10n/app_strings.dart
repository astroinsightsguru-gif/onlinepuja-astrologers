/// Supported top Indian languages across OnlinePuja ecosystem
enum AppLanguage {
  en('English', 'en', 'English'),
  hi('हिन्दी', 'hi', 'Hindi'),
  sa('संस्कृतम्', 'sa', 'Sanskrit'),
  gu('ગુજરાતી', 'gu', 'Gujarati'),
  mr('मराठी', 'mr', 'Marathi'),
  bn('বাংলা', 'bn', 'Bengali'),
  ta('தமிழ்', 'ta', 'Tamil'),
  te('తెలుగు', 'te', 'Telugu'),
  kn('ಕನ್ನಡ', 'kn', 'Kannada'),
  ml('മലയാളം', 'ml', 'Malayalam'),
  or('ଓଡ଼ିଆ', 'or', 'Odia'),
  pa('ਪੰਜਾਬੀ', 'pa', 'Punjabi'),
  as_('অসমীয়া', 'as', 'Assamese'),
  bho('भोजपुरी', 'bho', 'Bhojpuri'),
  mai('मैथिली', 'mai', 'Maithili');

  final String label;
  final String code;
  final String englishName;

  const AppLanguage(this.label, this.code, this.englishName);

  static AppLanguage fromCode(String? code) {
    if (code == null) return AppLanguage.en;
    final normalized = code.toLowerCase().trim();
    return AppLanguage.values.firstWhere(
      (e) => e.code == normalized || e.name == normalized,
      orElse: () => AppLanguage.en,
    );
  }
}

/// Global Reactive Localization Manager
class LocaleManager {
  LocaleManager._();
  static final LocaleManager instance = LocaleManager._();

  static const _kPrefLang = 'selected_app_language';
  final ValueNotifier<AppLanguage> currentLanguage =
      ValueNotifier<AppLanguage>(AppLanguage.en);

  Future<void> init() async {
    try {
      final sp = await SharedPreferences.getInstance();
      final code = sp.getString(_kPrefLang);
      if (code != null) {
        currentLanguage.value = AppLanguage.fromCode(code);
      }
    } catch (_) {}
  }

  Future<void> setLanguage(AppLanguage lang) async {
    currentLanguage.value = lang;
    try {
      final sp = await SharedPreferences.getInstance();
      await sp.setString(_kPrefLang, lang.code);
    } catch (_) {}
  }
}

